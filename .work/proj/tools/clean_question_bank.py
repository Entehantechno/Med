def clean_text(s):
    if not s or not isinstance(s, str):
        return s
    # 1. Clean watermarks
    s = WATERMARK_PAT.sub("", s)
    # 2. Typography
    for old, new in TYPOS:
        s = s.replace(old, new)
    # 3. Clean specific rogue double colons
    s = re.sub(r"::\s*", ": ", s)
    return s.strip()


