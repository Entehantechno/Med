def update_payload():
    path = "work/tools/master-bank/import-payload.master-preint.part08.json"
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)

    questions = data.get("questions", [])
    updated = 0
    for idx, item in BATCH_DATA.items():
        if idx < len(questions):
            q = questions[idx]
            q["question_fa"] = item["q_fa"]
            q["options_fa"] = item["opts"]
            q["correct_index"] = item["ci"]
            q["options_why_fa"] = item["whys"]
            q["explanation_fa"] = item["expl"]
            q["micro"] = {
                "lead_fa": item["micro"]["lead_fa"],
                "golden_fa": item["micro"]["golden_fa"],
                "points_fa": item["micro"]["points_fa"],
                "points_en": [],
                "options_fa": [],
                "options_en": [],
                "source_fa": "",
                "source_en": "",
                "media": None
            }
            updated += 1

    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"Successfully enriched {updated} questions in {path}.")

if __name__ == "__main__":
    update_payload()
