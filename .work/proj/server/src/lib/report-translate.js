/* report-translate.js — the translatable text of a virtual-patient report.

   The VP report is generated by AI (microlearning, strengths, weaknesses,
   suggestion) or derived from authored checklist labels in the language that
   was active when the attempt was graded. When the learner switches the site
   language, that text must follow the site language. Translating costs AI
   tokens, so the client caches every result in the browser (IndexedDB) keyed
   by attempt + language pair + a hash of the source text.

   This module only describes the SHAPE of the bundle: which fields are
   translatable, how they are read from a public (visibility-filtered)
   evaluation, how a translated bundle is validated, and how it is applied
   back. The AI call itself lives in ai-engine.js (translateReportBundle). */

const LIST_KEYS = ["strengths", "weaknesses", "missed", "commonMistakes"];
const ORDER_KEYS = ["appropriate", "unnecessary", "missedKey"];

const str = (v) => (typeof v === "string" ? v : "");
const arrOfStr = (v) => (Array.isArray(v) ? v.map(str) : []);

/* Build the source bundle from a PUBLIC evaluation (already filtered by
   showAi / showMicro, so hidden sections are never sent to the translator). */
export function extractReportBundle(ev) {
  if (!ev || typeof ev !== "object") return {};
  const bundle = {};
  if (str(ev.microlearning).trim()) bundle.microlearning = str(ev.microlearning);
  if (str(ev.suggestion).trim()) bundle.suggestion = str(ev.suggestion);
  for (const k of LIST_KEYS) {
    const list = arrOfStr(ev[k]);
    if (list.some((x) => x.trim())) bundle[k] = list;
  }
  if (Array.isArray(ev.results) && ev.results.length) {
    const rows = ev.results.map((r) => ({ label: str(r?.label), reason: str(r?.reason) }));
    if (rows.some((r) => r.label.trim() || r.reason.trim())) bundle.results = rows;
  }
  const sections = Array.isArray(ev.sectionScores?.sections) ? ev.sectionScores.sections.map((s) => str(s?.label)) : [];
  if (sections.some((x) => x.trim())) bundle.sectionLabels = sections;
  if (ev.orderReview && typeof ev.orderReview === "object") {
    const ob = {};
    for (const k of ORDER_KEYS) {
      const list = arrOfStr(ev.orderReview[k]);
      if (list.some((x) => x.trim())) ob[k] = list;
    }
    if (Object.keys(ob).length) bundle.orderReview = ob;
  }
  return bundle;
}

const sameShapeList = (a, b) => Array.isArray(b) && b.length === a.length
  && a.every((x, i) => (!x.trim() || (typeof b[i] === "string" && b[i].trim().length > 0)));

/* A translation is accepted only when every non-empty source field came back
   with the same structure (same keys, same array lengths, non-empty strings).
   Anything else is rejected so a malformed model answer can never blank or
   scramble the report. */
export function validateTranslatedBundle(source, translated) {
  if (!translated || typeof translated !== "object" || Array.isArray(translated)) return false;
  if (source.microlearning && !(typeof translated.microlearning === "string" && translated.microlearning.trim())) return false;
  if (source.suggestion && !(typeof translated.suggestion === "string" && translated.suggestion.trim())) return false;
  for (const k of LIST_KEYS) if (source[k] && !sameShapeList(source[k], translated[k])) return false;
  if (source.sectionLabels && !sameShapeList(source.sectionLabels, translated.sectionLabels)) return false;
  if (source.results) {
    const t = translated.results;
    if (!Array.isArray(t) || t.length !== source.results.length) return false;
    for (let i = 0; i < t.length; i++) {
      const s = source.results[i];
      if (!t[i] || typeof t[i] !== "object") return false;
      if (s.label.trim() && !(typeof t[i].label === "string" && t[i].label.trim())) return false;
      if (s.reason.trim() && !(typeof t[i].reason === "string" && t[i].reason.trim())) return false;
    }
  }
  if (source.orderReview) {
    for (const k of ORDER_KEYS) {
      if (source.orderReview[k] && !sameShapeList(source.orderReview[k], translated.orderReview?.[k])) return false;
    }
  }
  return true;
}

/* Return a copy of the public evaluation with the translated text in place of
   the source text. Everything that is not part of the bundle (scores, ids,
   xpReward, meta, flags) is kept exactly as it was. */
export function applyTranslatedBundle(ev, translated) {
  const out = { ...ev };
  if (translated.microlearning !== undefined) out.microlearning = translated.microlearning;
  if (translated.suggestion !== undefined) out.suggestion = translated.suggestion;
  for (const k of LIST_KEYS) if (translated[k] !== undefined) out[k] = translated[k];
  if (Array.isArray(translated.results) && Array.isArray(ev.results)) {
    out.results = ev.results.map((r, i) => ({ ...r, label: translated.results[i].label, reason: r?.reason ? translated.results[i].reason : r?.reason }));
  }
  if (Array.isArray(translated.sectionLabels) && ev.sectionScores?.sections) {
    out.sectionScores = { ...ev.sectionScores, sections: ev.sectionScores.sections.map((s, i) => ({ ...s, label: translated.sectionLabels[i] })) };
  }
  if (translated.orderReview && ev.orderReview) {
    out.orderReview = { ...ev.orderReview };
    for (const k of ORDER_KEYS) if (translated.orderReview[k] !== undefined) out.orderReview[k] = translated.orderReview[k];
  }
  return out;
}

/* Per-user translation budget. In-memory is deliberate: it stops a runaway
   client from burning AI tokens; it is not a billing record. */
const buckets = new Map();
export function takeTranslationBudget(userId, now = Date.now()) {
  const max = Math.max(1, Number(process.env.REPORT_TRANSLATE_PER_HOUR) || 20);
  const windowMs = 60 * 60 * 1000;
  const b = buckets.get(userId) || { start: now, n: 0 };
  if (now - b.start >= windowMs) { b.start = now; b.n = 0; }
  if (b.n >= max) { buckets.set(userId, b); return false; }
  b.n += 1;
  buckets.set(userId, b);
  return true;
}
