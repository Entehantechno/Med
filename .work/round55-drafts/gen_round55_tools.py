missing = {t for t in {v['topic'] for v in ITEMS.values()} if t not in SHARED}
LESSONS = {}
for topic in sorted({v['topic'] for v in ITEMS.values()}):
    if topic in SHARED:
        LESSONS[topic] = SHARED[topic]
        continue
    row = next(v for (_, n), v in sorted(ITEMS.items(), key=lambda kv: kv[0][1])
               if v['topic'] == topic)
    LESSONS[topic] = {'lesson': row['interpretation'], 'golden': row['lead'],
                      'points': list(row['reasons'])}

for (part, n), item in ITEMS.items():
    unit = LESSONS[item['topic']]
    assert len(item['interpretation'] + '\n\n' + unit['lesson']) > 300, (n, len(item['interpretation']), len(unit['lesson']))

for topic, unit in LESSONS.items():
    assert len(unit['points']) == 4, topic
    assert len(set(unit['points'])) == 4, topic
    assert all(len(pt) > 20 for pt in unit['points']), topic
    assert len(unit['lesson']) > 150, (topic, len(unit['lesson']))
    assert len(unit['golden']) > 20, topic


def dump_items():
    lines = ['# -*- coding: utf-8 -*-',
             '"""Round55 authored items — part29 rows 1-220 except 8 deferred (1393-1395 sittings).',
             'question_fa/options_fa NEVER touched; mirrors round53/54 schema:',
             'topic -> round55_lessons.LESSONS key · lead -> micro.lead_fa ·',
             'interpretation -> explanation_fa head · reasons -> 4 in printed option order,',
             'the enricher prefixes the payload correct_index entry with «گزینه صحیح: »."""',
             '',
             'ITEMS = {']
    for (part, n), item in sorted(ITEMS.items(), key=lambda kv: kv[0][1]):
        lines.append(f' (29, {n}): {{')
        for field in ('topic', 'lead', 'interpretation'):
            lines.append(f'  "{field}": {json.dumps(item[field], ensure_ascii=False)},')
        lines.append('  "reasons": [')
        for reason in item['reasons']:
            lines.append(f'  {json.dumps(reason, ensure_ascii=False)},')
        lines.append('],')
        lines.append(' },')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def dump_lessons():
    lines = ['# -*- coding: utf-8 -*-',
             '"""Round55 shared clinical units (part29 rows 1-220).',
             '',
             'One unit per authored topic: rows that share a topic share the SAME unit, so',
             'the twelve shared topics carry a general teaching unit authored here instead of',
             'a copy of one row\'s case text. Lesson language is Persian-first; Latin appears',
             'only where the standard term itself is the established name."""',
             '',
             'LESSONS = {']
    for topic in sorted(LESSONS):
        unit = LESSONS[topic]
        lines.append(f' {json.dumps(topic, ensure_ascii=False)}: {{')
        lines.append(f'  "lesson": {json.dumps(unit["lesson"], ensure_ascii=False)},')
        lines.append(f'  "golden": {json.dumps(unit["golden"], ensure_ascii=False)},')
        lines.append('  "points": [')
        for point in unit['points']:
            lines.append(f'  {json.dumps(point, ensure_ascii=False)},')
        lines.append('],')
        lines.append(' },')
    lines.append('}')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    (TOOLS / 'round55_items.py').write_text(dump_items(), encoding='utf-8')
    (TOOLS / 'round55_lessons.py').write_text(dump_lessons(), encoding='utf-8')
    print(f'items: {len(ITEMS)}  lessons: {len(LESSONS)}  '
          f'shared-topic units: {len(SHARED)}  missing defaults: {len(missing)}')
