def load(i):
    spec=importlib.util.spec_from_file_location(f"b{i}", f"{DRAFTS}/r54_b{i}.py")
    m=importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    return m.BATCH

def fix(text):
    for bad, good in REPAIRS + EXTRA + UNIT_REPAIRS:
        if bad and bad != good and bad in text:
            text = text.replace(bad, good)
    text = text.translate(DIGIT_MAP)
    text = re.sub(r'([۰-۹]+)\s*٫\s*([۰-۹]+)', r'\1٫\2', text)
    text = re.sub(r'([۰-۹])([0-9])', lambda m: m.group(1)+m.group(2).translate(str.maketrans('0123456789','۰۱۲۳۴۵۶۷۸۹')), text)
    text = re.sub(r'([0-9])([۰-۹])', lambda m: m.group(1).translate(str.maketrans('0123456789','۰۱۲۳۴۵۶۷۸۹'))+m.group(2), text)
    text = text.replace('  ', ' ')
    return text

def ser(value, indent=0):
    pad=' '*indent
    if isinstance(value, dict):
        items=[]
        for k,v in value.items():
            items.append(f"{pad}  ({k[0]}, {k[1]}): {{\n"+ "".join(
                f"{pad}   \"{key}\": {json.dumps(val, ensure_ascii=True)},\n" for key,val in v.items()) + f"{pad}  }},")
        return "{\n"+"\n".join(items)+f"\n{pad}}}"
    raise TypeError(value)

